@dataclass(frozen=True)
class DayModifiers:
    """How one day departs from ordinary training.

    Every field is a dial on the ordinary generation path. The default value of
    each is the ordinary behaviour, so a day with no scenario active is
    generated by identical code to one with several.
    """

    # --- programme ---
    volume_multiplier: float = 1.0
    rir_offset: float = 0.0
    force_rest: bool = False
    force_substitution: bool = False
    # --- recovery ---
    sleep_override_h: float | None = None
    temperature_offset: float = 0.0
    steps_override: float | None = None
    stress_shock: float = 0.0
    recovery_bonus: float = 0.0
    # --- performance ---
    adaptation_multiplier: float = 1.0
    force_bad_session: bool = False

    def merged_with(self, other: "DayModifiers") -> "DayModifiers":
        """Combine two scenarios active on the same day.

        Multiplicative dials compose, additive offsets add, flags take the
        stronger. Overlapping scenarios are rare but the chronology does place
        a novelty block inside ordinary training.
        """
        return DayModifiers(
            volume_multiplier=self.volume_multiplier * other.volume_multiplier,
            rir_offset=self.rir_offset + other.rir_offset,
            force_rest=self.force_rest or other.force_rest,
            force_substitution=self.force_substitution or other.force_substitution,
            sleep_override_h=(
                other.sleep_override_h if other.sleep_override_h is not None
                else self.sleep_override_h
            ),
            temperature_offset=self.temperature_offset + other.temperature_offset,
            steps_override=(
                other.steps_override if other.steps_override is not None
                else self.steps_override
            ),
            stress_shock=self.stress_shock + other.stress_shock,
            recovery_bonus=self.recovery_bonus + other.recovery_bonus,
            adaptation_multiplier=self.adaptation_multiplier * other.adaptation_multiplier,
            force_bad_session=self.force_bad_session or other.force_bad_session,
        )


@dataclass(frozen=True)
class ScenarioWindow:
    """One scheduled scenario: what it is, when, and what it should do."""

    scenario: Scenario
    first_day: int
    last_day: int
    modifiers: DayModifiers
    intended_effect: str

    def __post_init__(self) -> None:
        if self.last_day < self.first_day:
            raise ValueError(f"{self.scenario.value}: window ends before it starts")

    def covers(self, day_index: int) -> bool:
        return self.first_day <= day_index <= self.last_day

    @property
    def duration_days(self) -> int:
        return self.last_day - self.first_day + 1


def _window(scenario, first, last, effect, **dials) -> ScenarioWindow:
    return ScenarioWindow(scenario, first, last, DayModifiers(**dials), effect)


