class ScenarioEngine:
    """Resolves which scenarios are active on a day and what they do."""

    #: Days 0-519 develop the engine; 520-729 are held back (``DATA.md`` §15).
    DEVELOPMENT_LAST_DAY = 519

    def __init__(self, schedule: tuple[ScenarioWindow, ...] = SCENARIO_SCHEDULE) -> None:
        self.schedule = schedule
        self._validate()

    def _validate(self) -> None:
        for window in self.schedule:
            if window.first_day < 0:
                raise ValueError(f"{window.scenario.value}: negative start day")
        # Two windows of the same scenario must not overlap; different
        # scenarios may, and the chronology relies on it.
        for i, first in enumerate(self.schedule):
            for second in self.schedule[i + 1:]:
                if first.scenario is second.scenario and not (
                    first.last_day < second.first_day or second.last_day < first.first_day
                ):
                    raise ValueError(
                        f"{first.scenario.value} scheduled twice over overlapping days"
                    )

    def active(self, day_index: int) -> tuple[ScenarioWindow, ...]:
        return tuple(w for w in self.schedule if w.covers(day_index))

    def modifiers_for(self, day_index: int) -> DayModifiers:
        """The combined effect of every scenario active on a day."""
        combined = DayModifiers()
        for window in self.active(day_index):
            combined = combined.merged_with(window.modifiers)
        return combined

    def labels_for(self, day_index: int) -> tuple[str, ...]:
        active = self.active(day_index)
        if not active:
            return (Scenario.ORDINARY.value,)
        return tuple(w.scenario.value for w in active)

    def windows_for(self, scenario: Scenario) -> tuple[ScenarioWindow, ...]:
        return tuple(w for w in self.schedule if w.scenario is scenario)

    def scenarios_present(self) -> frozenset[Scenario]:
        return frozenset(w.scenario for w in self.schedule) | {Scenario.ORDINARY}

    def in_development_window(self, day_index: int) -> bool:
        return day_index <= self.DEVELOPMENT_LAST_DAY

    def manifest_rows(self) -> list[dict[str, object]]:
        """Rows for ``hidden/scenario_manifest.csv``.

        Simulator-only. An engine that knew a deload was coming would not be
        inferring anything.
        """
        return [
            {
                "scenario": w.scenario.value,
                "first_day": w.first_day,
                "last_day": w.last_day,
                "duration_days": w.duration_days,
                "window": "development" if self.in_development_window(w.first_day) else "holdout",
                "volume_multiplier": w.modifiers.volume_multiplier,
                "rir_offset": w.modifiers.rir_offset,
                "sleep_override_h": w.modifiers.sleep_override_h,
                "steps_override": w.modifiers.steps_override,
                "temperature_offset": w.modifiers.temperature_offset,
                "intended_effect": w.intended_effect,
            }
            for w in sorted(self.schedule, key=lambda w: w.first_day)
        ]
