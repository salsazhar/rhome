"""Scenario engine (``DATA.md`` §13, §14).

The dataset deliberately contains episodes that test specific model behaviour:
accumulation blocks, deloads, sleep restriction, illness, travel, plateaus and
unexplained bad days. Each has a documented intended effect on the latent
state, and each is asserted rather than assumed.

Scenarios are expressed as **modifiers on the ordinary generation path**, never
as separate code branches. A sleep-restricted day runs through exactly the same
sleep model as any other day, with a different target; a deload week runs
through the same programme generator with a lower volume multiplier. Branching
would risk scenario days differing from ordinary days in ways nobody intended,
and would make the scenario the thing being tested rather than the model's
response to it.

The manifest this module produces is simulator-only. ``DATA.md`` §6.3 places it
in the hidden output alongside the latent tables: an engine that knew a deload
was coming would not be inferring anything.
"""

