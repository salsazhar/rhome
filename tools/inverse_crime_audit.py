# Engine forms, from MODEL.tex, reproduced here for comparison only.
PHI_F = {0: 1.35, 1: 1.15, 2: 1.00, 3: 0.90, 4: 0.82}
def engine_effort(q): return PHI_F.get(int(q), 0.75)
def engine_volume(r): return min(max(0.80 + 0.02 * r, 0.86), 1.20)


def session(sets=4, reps=5, rir=1.0, exercise="back_squat", state=None):
    p = Physiology(athlete, state=state)
    p.begin_session()
    for _ in range(sets):
        p.apply_set(lib[exercise], reps=reps, true_rir=rir,
                    relative_intensity=0.85, exposure_count=50)
    return p


