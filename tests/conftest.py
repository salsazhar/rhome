"""Shared test fixtures and the spec-marker collector.

Collects every ``@pytest.mark.spec(...)`` marker during the run and writes the
conformance report to ``build_log/conformance.md`` at the end of the session,
so Guardrail 5 is refreshed by simply running the tests.
"""

from __future__ import annotations

from collections import defaultdict
from pathlib import Path

import pytest

from rhome_core.conformance import CLAUSES, coverage_report

_MARKED: dict[str, list[str]] = defaultdict(list)

REPO_ROOT = Path(__file__).resolve().parents[1]


def pytest_collection_modifyitems(items):
    for item in items:
        for marker in item.iter_markers(name="spec"):
            for clause_id in marker.args:
                _MARKED[clause_id].append(item.nodeid)


def pytest_sessionfinish(session, exitstatus):
    # Only write a full report when the whole suite ran, so a filtered run
    # cannot overwrite the report with partial coverage. Naming a single file
    # on the command line counts as filtering: it is the ordinary way to
    # re-run one stage's tests, and it silently rewrote the report to 0%
    # coverage until this check looked at the arguments as well as the flags.
    if session.config.option.keyword or session.config.option.markexpr:
        return
    whole_suite = {REPO_ROOT, REPO_ROOT / "tests"}
    for argument in session.config.args:
        path = Path(argument.split("::")[0]).resolve()
        if path not in whole_suite:
            return

    report = coverage_report(dict(_MARKED))
    lines = [
        "# Specification conformance report",
        "",
        "Generated by the test suite (Guardrail 5). Do not edit by hand.",
        "",
        f"**Clauses registered:** {len(CLAUSES)}",
        f"**Covered:** {len(report.covered)}",
        f"**Uncovered:** {len(report.uncovered)}",
        f"**Coverage:** {report.coverage_fraction:.0%}",
        "",
        "## Covered",
        "",
        "| Clause | Document | Section | Layer | Tests |",
        "|---|---|---|---|---|",
    ]
    for clause_id, tests in report.covered.items():
        c = CLAUSES[clause_id]
        shown = "<br>".join(t.split("::")[-1] for t in tests)
        lines.append(f"| `{clause_id}` | {c.document} | {c.section} | {c.layer} | {shown} |")

    if report.uncovered:
        lines += ["", "## Uncovered — visible gaps", "",
                  "| Clause | Document | Section | Layer | Statement |", "|---|---|---|---|---|"]
        for clause_id in report.uncovered:
            c = CLAUSES[clause_id]
            lines.append(
                f"| `{clause_id}` | {c.document} | {c.section} | {c.layer} | {c.statement} |"
            )
    else:
        lines += ["", "## Uncovered — visible gaps", "", "None."]

    if report.unknown_clauses:
        lines += ["", "## Tests claiming unregistered clauses", ""]
        for clause_id, tests in report.unknown_clauses.items():
            lines.append(f"- `{clause_id}` claimed by {', '.join(tests)}")

    out = REPO_ROOT / "build_log" / "conformance.md"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
